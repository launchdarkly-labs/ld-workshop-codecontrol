#!/usr/bin/env bash
#
# Assembles a self-contained image.sh:
#   image.base.sh  +  every file under ./app embedded as a heredoc  +  app-install.sh
#
# Re-run after ANY change to ./app so image.sh stays in sync. Files under
# ./app/.venv and *.pyc are skipped. The embedded section installs to
# $APP_DIR (default /opt/ld/app); override APP_DIR when testing extraction.
#
set -euo pipefail
cd "$(dirname "$0")"
OUT="image.sh"
MARK="__LD_APP_FILE__"

{
  cat image.base.sh
  echo
  echo "# ============ Demo app files (generated by build-image.sh from ./app) ============"
  echo 'APP_DIR="${APP_DIR:-/opt/ld/app}"'
  echo 'mkdir -p "$APP_DIR"'
  find app -type f ! -path '*/.venv/*' ! -path '*/__pycache__/*' ! -name '*.pyc' ! -name '.gitignore' | LC_ALL=C sort | while IFS= read -r f; do
    if grep -qF "$MARK" "$f"; then
      echo "ERROR: $f contains the heredoc marker $MARK" >&2
      exit 1
    fi
    rel="${f#app/}"
    echo
    echo "mkdir -p \"\$APP_DIR/$(dirname "$rel")\""
    echo "cat > \"\$APP_DIR/$rel\" <<'$MARK'"
    cat "$f"
    [ -n "$(tail -c1 "$f")" ] && echo
    echo "$MARK"
  done
  echo
  cat app-install.sh
} > "$OUT"

chmod +x "$OUT"
bash -n "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
