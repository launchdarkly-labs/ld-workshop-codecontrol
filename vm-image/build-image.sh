#!/usr/bin/env bash
#
# Assembles a self-contained image.sh = image.base.sh + app-install.sh, the
# shape the launchdarkly-instruqt-track skill expects (its stock variant also
# embeds ./app as heredocs; this workshop's app is placed from git instead
# because it vendors ~1 MB of browser bundles). Re-run after ANY change to
# image.base.sh or app-install.sh so image.sh stays in sync; image.sh is what
# gets executed on the host image.
#
set -euo pipefail
cd "$(dirname "$0")"
OUT="image.sh"
{
  cat image.base.sh
  echo
  echo "# ============ Workshop app (generated by build-image.sh from ./app-install.sh) ============"
  cat app-install.sh
} > "$OUT"
chmod +x "$OUT"
bash -n "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
